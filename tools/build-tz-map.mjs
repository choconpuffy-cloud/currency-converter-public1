// Regenerates tz-map.js (IANA time zone -> ISO country) from the system tzdata.
// Usage: node tools/build-tz-map.mjs > tz-map.js
import { readFileSync } from 'node:fs';
const dir = '/usr/share/zoneinfo';
const map = {};
for (const line of readFileSync(`${dir}/zone.tab`, 'utf8').split('\n')) {
  if (!line || line.startsWith('#')) continue;
  const [cc, , tz] = line.split('\t');
  map[tz] = cc;
}
// Legacy aliases (e.g. Asia/Saigon -> Asia/Ho_Chi_Minh) inherit the target's country.
for (const line of readFileSync(`${dir}/tzdata.zi`, 'utf8').split('\n')) {
  const [kind, target, alias] = line.split(' ');
  if (kind === 'L' && map[target] && !map[alias]) map[alias] = map[target];
}
const sorted = Object.fromEntries(Object.entries(map).sort());
console.log('// Generated by tools/build-tz-map.mjs — do not edit by hand.');
console.log(`export const TZ_TO_COUNTRY = ${JSON.stringify(sorted)};`);
